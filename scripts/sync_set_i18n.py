def patch_lang(lang: str) -> int:
    path = ROOT / "lang" / f"{lang}.php"
    current = parse_lang(path)
    de = parse_lang(ROOT / "lang" / "de.php")
    focus = [k for k in de if k.startswith(PREFIXES)]
    trans = TRANSLATIONS.get(lang, {})
    missing = []
    for key in focus:
        if key in current:
            continue
        value = trans.get(key) or (parse_lang(ROOT / "lang" / "en.php").get(key) if lang != "en" else None) or de[key]
        missing.append((key, value))
    if not missing:
        return 0
    block = "\n    // Layout sets / Logos (synced)\n"
    for key, value in missing:
        block += f"    '{key}' => '{php_escape(value)}',\n"
    text = path.read_text(encoding="utf-8")
    marker = "    'common.save'"
    if marker not in text:
        raise SystemExit(f"Marker not found in {path}")
    text = text.replace(marker, block + "\n" + marker, 1)
    path.write_text(text, encoding="utf-8")
    return len(missing)


def main() -> None:
    total = 0
    for lang in ("en", "fr", "it", "rm"):
        n = patch_lang(lang)
        print(f"{lang}: +{n} keys")
        total += n
    print(f"total: {total}")


if __name__ == "__main__":
    main()
